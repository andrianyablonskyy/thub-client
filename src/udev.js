'use strict';

const fs = require('node:fs'),
  path = require('node:path'),
  { execFileSync } = require('node:child_process'),
  { splitUdevFilter, udevFilterOf, LIST_KINDS } = require('@andrian.yablonskyy/thub-common'),
  { hwLockHolder } = require('./hw-lock');

const RULES_DIR = '/etc/udev/rules.d',
  // One file for the machine: only one HW Client runs on it (hw-lock.js).
  RULES_FILE = '99-thub-client-hw.rules',
  // The first line of every file the Client writes — how an older one's
  // 99-thub-<instance>.rules is told from a rule written by hand.
  HEADER = '# Generated by thub-client',
  SETTLE_TIMEOUT_SEC = 10,

  // uhubctl (hw-devices.usbPower, README §8.7) switches a port through its
  // hub's sysfs `<port>/disable` file (Linux 6+) or over libusb (older):
  // the service runs as an ordinary user in plugdev, so give that group
  // both — for every USB hub, since uhubctl also switches a USB3 hub's
  // USB2 twin, whose location isn't in the config.
  HUB_POWER_RULE = 'SUBSYSTEM=="usb", DRIVER=="usb", ATTR{bDeviceClass}=="09", MODE="0664", GROUP="plugdev", ' +
    'RUN+="/bin/sh -c \'chgrp -f plugdev $sys$devpath/*-port*/disable; chmod -f g+w $sys$devpath/*-port*/disable; true\'"';

function rulesFile(rulesDir = RULES_DIR){
  return path.join(rulesDir, RULES_FILE);
}

// The symlink ends up inside "..." in a udev rule: nothing that could break
// out of the quotes or smuggle in another key.
function symlinkOf(field, devicePath){
  if (typeof devicePath !== 'string' || !/^\/dev\/[\w.:+/-]+$/.test(devicePath)){
    throw new Error(`${field}.path must be under /dev/ to get a udev symlink, got ${JSON.stringify(devicePath)}`);
  }
  return devicePath.slice('/dev/'.length);
}

// One rule per hw-devices entry with a udev filter (README §8.6): its own
// `udev` (matches, and maybe MODE/GROUP/OWNER/TAG+= for the device node's
// access), or the filter of an older entry's devpath and ids; its symlink is
// the filter's SYMLINK+="…" if it has one, else the entry's path. The filter is
// checked again here, as this file is installed as root. Entries without
// one are left to whatever already provides their `path` (a manual rule, or
// a plain /dev node), so they get no rule here.
function ruleLines(hw){
  const lines = [];
  for (const [list, kind]of Object.entries(LIST_KINDS)){
    (hw[list] || []).forEach((entry, i) => {
      const filter = udevFilterOf(entry, kind);
      if (!filter){
        return;
      }
      const field = `hw-devices.${list}[${i}]`;
      let parts;
      try {
        parts = splitUdevFilter(filter);
      }
      catch (err){
        throw new Error(`${field}.udev: ${err.message}`);
      }
      // Its access assignments (MODE, GROUP, …) as given; its own
      // SYMLINK+="…" overrides thub/dut<index>-<kind>.
      lines.push(`${parts.match}, ${parts.assign ? `${parts.assign}, ` : ''}SYMLINK+="${parts.symlink ?? symlinkOf(field, entry.path)}"`);
    });
  }
  if (hw.usbPower?.ports?.length){
    lines.push(HUB_POWER_RULE);
  }
  return lines;
}

// null when the Client needs no rules at all (SW Client, or no entry with
// a udev filter and no USB power ports) — the rule file, if any, is then
// removed: an emptied device list leaves no rule behind.
function renderRules({ instance, type, hw }){
  const lines = type === 'hw' ? ruleLines(hw || {}) : [];
  if (!lines.length){
    return null;
  }
  return [
    `${HEADER} for instance "${instance}" from its config's hw-devices section.`,
    '# Rewritten on every Client start — edit the config, not this file.',
    ...lines,
    ''
  ].join('\n');
}

function readFileOrNull(file){
  try {
    return fs.readFileSync(file, 'utf8');
  }
  catch {
    return null;
  }
}

function isRoot(){
  return typeof process.getuid === 'function' && process.getuid() === 0;
}

// The other 99-thub*.rules files in the rules directory: { generated }
// (an older Client's per-instance file, removed on sync) or { manual }
// (written by hand: kept, but its symlinks are checked against ours).
function otherRuleFiles(rulesDir){
  let files = [];
  try {
    files = fs.readdirSync(rulesDir).filter((f) => /^99-thub(-.+)?\.rules$/.test(f) && f !== RULES_FILE);
  }
  catch {
    return { generated: [], manual: [] };
  }
  const generated = [],
    manual = [];
  for (const f of files){
    const file = path.join(rulesDir, f);
    ((readFileOrNull(file) || '').startsWith(HEADER) ? generated : manual).push(file);
  }
  return { generated, manual };
}

// Symlinks our rules claim that a hand-written rule file also claims —
// udev would pick either one.
function findConflicts(content, manual){
  const own = new Set([...content.matchAll(/SYMLINK\+="([^"]+)"/g)].map((m) => m[1])),
    conflicts = [];
  for (const file of manual){
    for (const [, link]of (readFileOrNull(file) || '').matchAll(/^[^#]*SYMLINK\+="([^"]+)"/gm)){
      if (own.has(link)){
        conflicts.push({ file, symlink: link });
      }
    }
  }
  return conflicts;
}

// Brings /etc/udev/rules.d/99-thub-client-hw.rules in line with the
// config: writes it, or removes it when the config has no rules (an SW
// Client, or every device removed on the dashboard); and removes the
// per-instance files older Clients wrote. Only when something differs:
// then it reloads udev and re-triggers USB/tty/block devices, so the
// symlinks (or their absence) are in place before the Client reports its
// capabilities. Returns what it did:
//   skipped    — not Linux
//   unchanged  — the rules already match the config
//   updated    — files written/removed and udev reloaded
//   needs-root — a change is needed but this process can't make it
// `rulesDir`/`root`/`reload`: for tests.
function syncUdevRules(cfg, { log = console, rulesDir = RULES_DIR, root = isRoot(), reload = reloadUdev, platform = process.platform } = {}){
  if (platform !== 'linux'){
    return { status: 'skipped' };
  }
  const file = rulesFile(rulesDir),
    content = renderRules(cfg),
    current = readFileOrNull(file),
    { generated, manual } = otherRuleFiles(rulesDir);

  if (content){
    for (const { file: other, symlink }of findConflicts(content, manual)){
      log.warn(`udev: ${other} also defines /dev/${symlink}.`);
    }
  }

  if (content === current && !generated.length){
    return { status: 'unchanged', file };
  }
  if (!root){
    return { status: 'needs-root', file };
  }

  if (content){
    fs.writeFileSync(file, content, { mode: 0o644 });
  }
  else {
    fs.rmSync(file, { force: true });
  }
  for (const old of generated){
    fs.rmSync(old, { force: true });
    log.log(`udev: removed ${old} (an older Client's; the rules are in ${file} now)`);
  }
  reload();
  log.log(content ? `udev: installed ${file}` : `udev: removed ${file} (no hw-devices entries with a udev filter)`);
  return { status: 'updated', file };
}

function reloadUdev(){
  execFileSync('udevadm', ['control', '--reload'], { stdio: 'ignore' });
  // `change`, not `add`: re-applies the rules (and so the symlinks)
  // without making anything else treat the devices as newly plugged in.
  for (const subsystem of ['usb', 'tty', 'block']){
    execFileSync('udevadm', ['trigger', '--action=change', `--subsystem-match=${subsystem}`], { stdio: 'ignore' });
  }
  execFileSync('udevadm', ['settle', `--timeout=${SETTLE_TIMEOUT_SEC}`], { stdio: 'ignore' });
}

// Whether `cfg`'s instance may write the machine's rules: an HW Client while
// no other HW Client holds the lock (hw-lock.js); an SW one never touches
// them. Resolves to { ok } or { ok: false, reason }.
async function mayWriteRules(cfg, { holder } = {}){
  if (cfg.type !== 'hw'){
    return { ok: false, reason: `instance "${cfg.instance}" is an SW Client: the machine's udev rules are the HW Client's` };
  }
  const running = holder !== undefined ? holder : await hwLockHolder();
  if (running && running !== cfg.instance){
    return { ok: false, reason: `the HW Client "${running}" runs on this machine; its rules stay` };
  }
  return { ok: true };
}

module.exports = { renderRules, syncUdevRules, mayWriteRules, rulesFile, HUB_POWER_RULE, RULES_FILE };

// systemd ExecStartPre=+ entry point (runs as root, before the daemon
// drops to its own user): `node udev.js --config <path>`.
// Never fails the unit — a bad udev setup shows up as missing devices on
// the resource card, which beats a Client that won't start at all.
if (require.main === module){
  const { loadDeviceConfig } = require('./config'),
    argv = process.argv.slice(2),
    flag = (name) => {
      const i = argv.indexOf(name);
      return i >= 0 ? argv[i + 1] : undefined;
    };
  (async () => {
    const cfg = loadDeviceConfig(flag('--config') || process.env.THUB_CLIENT_CONFIG),
      may = await mayWriteRules(cfg);
    if (!may.ok){
      console.warn(`udev: left alone — ${may.reason}`);
      return;
    }
    const { status, file } = syncUdevRules(cfg);
    if (status === 'needs-root'){
      console.warn(`udev: ${file} is out of date but this is not running as root`);
    }
  })().catch((err) => {
    console.error(`udev: ${err.message}`);
  });
}
